declare(strict_types=1);

namespace pocketmine\entity\riding;

/**
 * Implemented by entities that can be mounted by other entities.
 */
interface Mountable{

	/**
	 * Returns this entity's passenger and seat link manager.
	 *
	 * Implementations must return the same instance across calls and initialize it during entity
	 * setup (e.g. in {@link Entity::initEntity()}) so that vehicle metadata is included in spawn packets.
	 */
	public function getLinkManager() : LinkManager;
}
